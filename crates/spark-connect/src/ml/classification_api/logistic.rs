/// The message of `thresholds` with other than two elements, as PySpark's getThreshold names it.
const BINARY_ONLY: &str =
    "Logistic Regression getThreshold only applies to binary classification, \
     but thresholds has length != 2.";

/// The doc of the `thresholds` param, as PySpark names it in the KeyError of an unset thresholds.
const THRESHOLDS_DOC: &str = "Thresholds in multi-class classification to adjust the probability \
     of predicting each class. Array must have length equal to the number of classes, with values \
     > 0, excepting that at most one value may be 0. The class with largest value p/t is \
     predicted, where p is the original probability of that class and t is the class's \
     threshold.";

/// The threshold of binary classification, as PySpark's `getThreshold` reads it: the equivalent
/// of `thresholds` when they are set (`1 / (1 + thresholds(0) / thresholds(1))`), else the
/// `threshold`, or its default.
fn threshold_of(params: &Params) -> Result<f64> {
    check_threshold_consistency(params)?;
    if params.get_param("thresholds").is_some() {
        return binary_equivalent(params);
    }
    Ok(params.double_or("threshold", 0.5))
}

/// The thresholds of the two classes, as PySpark's `getThresholds` reads them: the `thresholds`
/// when they are set, else `(1 - threshold, threshold)`. An error when neither is set, which is
/// PySpark's KeyError of the param.
fn thresholds_of(uid: &str, params: &Params) -> Result<Vec<f64>> {
    check_threshold_consistency(params)?;
    if params.get_param("thresholds").is_none() && params.get_param("threshold").is_some() {
        let threshold = params.double_or("threshold", 0.5);
        return Ok(vec![1.0 - threshold, threshold]);
    }
    params.double_array_opt("thresholds").ok_or_else(|| {
        SparkError::value_msg(format!(
            "Param(parent='{uid}', name='thresholds', doc=\"{THRESHOLDS_DOC}\")"
        ))
    })
}

/// The binary equivalent of the thresholds, as `getThreshold` computes it after the consistency
/// check: an error unless there are two thresholds.
fn binary_equivalent(params: &Params) -> Result<f64> {
    let thresholds = params.double_array_opt("thresholds").unwrap_or_default();
    if thresholds.len() != 2 {
        return Err(SparkError::value_msg(format!(
            "{BINARY_ONLY}  thresholds: {thresholds:?}"
        )));
    }
    Ok(1.0 / (1.0 + thresholds[0] / thresholds[1]))
}

/// `_checkThresholdConsistency` of PySpark: when both the threshold and the thresholds are set,
/// the thresholds must be binary and agree with the threshold to 1e-5.
fn check_threshold_consistency(params: &Params) -> Result<()> {
    if params.get_param("threshold").is_none() || params.get_param("thresholds").is_none() {
        return Ok(());
    }
    let thresholds = params.double_array_opt("thresholds").unwrap_or_default();
    if thresholds.len() != 2 {
        return Err(SparkError::value_msg(format!(
            "{BINARY_ONLY} thresholds: {thresholds:?}"
        )));
    }
    let equivalent = 1.0 / (1.0 + thresholds[0] / thresholds[1]);
    let threshold = params.double_or("threshold", 0.5);
    if (threshold - equivalent).abs() >= 1e-5 {
        return Err(SparkError::value_msg(format!(
            "Logistic Regression getThreshold found inconsistent values for threshold ({}) \
             and thresholds (equivalent to {})",
            format_g(threshold),
            format_g(equivalent)
        )));
    }
    Ok(())
}

/// Python's `%g` of a float: six significant digits, without trailing zeros, in exponent form
/// outside `1e-4 <= |x| < 1e6`.
fn format_g(value: f64) -> String {
    if value.is_nan() {
        return "nan".to_string();
    }
    if value.is_infinite() {
        return if value > 0.0 { "inf" } else { "-inf" }.to_string();
    }
    if value == 0.0 {
        return "0".to_string();
    }
    let scientific = format!("{value:.5e}");
    let (mantissa, exponent) = scientific.split_once('e').expect("scientific form");
    let exponent: i32 = exponent.parse().expect("exponent");
    if (-4..6).contains(&exponent) {
        let decimals = (5 - exponent) as usize;
        trim_zeros(&format!("{value:.decimals$}"))
    } else {
        let sign = if exponent < 0 { '-' } else { '+' };
        format!(
            "{}e{sign}{:02}",
            trim_zeros(mantissa),
            exponent.unsigned_abs()
        )
    }
}

/// `text` without the trailing zeros of its fraction, and without a trailing point.
fn trim_zeros(text: &str) -> String {
    if text.contains('.') {
        text.trim_end_matches('0').trim_end_matches('.').to_string()
    } else {
        text.to_string()
    }
}

// PySpark's setThreshold and setThresholds leave the other param set: over Spark Connect the
// `clear` of `pyspark.ml` does nothing, so a threshold and thresholds that disagree raise the
// error of their getters.
impl LogisticRegression {
    /// Set the threshold of binary classification (`setThreshold`).
    pub fn set_threshold(mut self, value: f64) -> Self {
        self.params = self.params.set_param_double("threshold", value);
        self
    }

    /// Set the thresholds of the classes (`setThresholds`).
    pub fn set_thresholds(mut self, values: impl IntoIterator<Item = f64>) -> Self {
        self.params = self.params.set_param_double_array("thresholds", values);
        self
    }

    /// The features column: the name of v4.2.0 of [`Self::features_col`].
    #[deprecated(
        since = "4.3.0",
        note = "use `features_col`, PySpark's `getFeaturesCol`"
    )]
    pub fn feature_col(&self) -> &str {
        self.features_col()
    }

    /// Set the features column: the name of v4.2.0 of [`Self::set_features_col`].
    #[deprecated(
        since = "4.3.0",
        note = "use `set_features_col`, PySpark's `setFeaturesCol`"
    )]
    pub fn set_feature_col(self, value: &str) -> Self {
        self.set_features_col(value)
    }
}

