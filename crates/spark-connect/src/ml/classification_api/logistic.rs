/// The matrix of a `Matrix` value of `method`.
fn as_matrix(method: &str, value: MlValue) -> Result<MlMatrix> {
    match value {
        MlValue::Matrix(matrix) => Ok(matrix),
        other => Err(SparkError::value_msg(format!(
            "expected a matrix of `{method}`, got {other:?}"
        ))),
    }
}
