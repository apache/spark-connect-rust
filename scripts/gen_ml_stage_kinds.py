"""Generate the tables of the ML meta-algorithms from tests/golden/ml_api.json:
- crates/spark-connect/src/ml/stage_kinds.rs: the kind of each JVM class of the stages of
  pyspark.ml (an estimator, a transformer, a model or an evaluator), which a load of a
  meta-algorithm of PySpark's Python format reads its stages by, as the server's `Read` of a JVM
  class needs its operator type;
- crates/spark-connect/src/ml/param_specs.rs: the converter of each param of each class (its
  `typeConverter` in pyspark.ml.param), the doc of each param (its `Param.doc`, which PySpark's
  message of an extraneous param shows), and the model class of each estimator whose model is not
  named with `Model` appended to its name.

    python scripts/gen_ml_stage_kinds.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# The classes of PySpark's Python format, which are no JVM classes.
PYTHON_CLASSES = {
    "Pipeline",
    "PipelineModel",
    "CrossValidator",
    "CrossValidatorModel",
    "TrainValidationSplit",
    "TrainValidationSplitModel",
    "OneVsRest",
    "OneVsRestModel",
}
# The converter of each golden converter of a param. A converter that takes a value as it is (of
# `identity`, `toVector` and `toMatrix`) is `Identity`.
CONVERTERS = {
    "toBoolean": "Boolean",
    "toFloat": "Float",
    "toInt": "Int",
    "toListFloat": "ListFloat",
    "toListInt": "ListInt",
    "toListListFloat": "ListListFloat",
    "toListString": "ListString",
    "toString": "String",
    "identity": "Identity",
    "toVector": "Identity",
    "toMatrix": "Identity",
}
# The estimators whose model is not named with `Model` appended to the estimator's name (the
# model of PySpark's `_create_model`), by their simple names.
MODEL_CLASSES = {
    "DecisionTreeClassifier": "DecisionTreeClassificationModel",
    "DecisionTreeRegressor": "DecisionTreeRegressionModel",
    "FMClassifier": "FMClassificationModel",
    "FMRegressor": "FMRegressionModel",
    "GBTClassifier": "GBTClassificationModel",
    "GBTRegressor": "GBTRegressionModel",
    "MultilayerPerceptronClassifier": "MultilayerPerceptronClassificationModel",
    "QuantileDiscretizer": "Bucketizer",
    "RandomForestClassifier": "RandomForestClassificationModel",
    "RandomForestRegressor": "RandomForestRegressionModel",
}


def kind(name, entry):
    members = entry["members"]
    if "fit" in members:
        return "Estimator"
    if "evaluate" in members and "isLargerBetter" in members:
        return "Evaluator"
    if "transform" in members:
        return "Model" if name.endswith("Model") else "Transformer"
    return None


def jvm_name(name, entry):
    return entry["module"].replace("pyspark", "org.apache.spark", 1) + "." + name


def stage_kinds(api):
    rows = []
    for name, entry in sorted(api.items()):
        k = kind(name, entry)
        if k is None or name in PYTHON_CLASSES:
            continue
        rows.append(f'    ("{jvm_name(name, entry)}", OperatorType::{k}),')
    out = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// @generated by scripts/gen_ml_stage_kinds.py from tests/golden/ml_api.json; do not edit.",
        "//! The kind of each JVM class of the stages of pyspark.ml 4.3.0, of which a load of a",
        "//! meta-algorithm reads its stages: the server's `Read` of a class needs its operator type.",
        "use super::OperatorType;",
        "",
        "/// Each JVM class of a stage of pyspark.ml and its operator type, by class name.",
        "#[rustfmt::skip]",
        "pub(super) const STAGE_KINDS: &[(&str, OperatorType)] = &[",
        *rows,
        "];",
        "",
    ]
    (ROOT / "crates/spark-connect/src/ml/stage_kinds.rs").write_text("\n".join(out))


def rust_str(text):
    """The Rust literal of a doc: printable ASCII, with the escapes of its quotes and newlines."""
    out = []
    for c in text:
        if c == '"':
            out.append('\\"')
        elif c == "\\":
            out.append("\\\\")
        elif c == "\n":
            out.append("\\n")
        elif " " <= c <= "~":
            out.append(c)
        else:
            raise SystemExit(f"a doc of a param has the character {c!r}, which the table lacks")
    return '"' + "".join(out) + '"'


def param_specs(api):
    # Each estimator of a JVM class has a model: the class of its name with `Model` appended, or
    # the one of MODEL_CLASSES. Each target must be a model of the golden file.
    models = {}
    for name, entry in api.items():
        if kind(name, entry) != "Estimator" or name in PYTHON_CLASSES:
            continue
        model = MODEL_CLASSES.get(name, name + "Model")
        if model not in api:
            raise SystemExit(f"{name}: its model {model} is not in the golden file")
        if name in MODEL_CLASSES:
            models[name] = jvm_name(model, api[model])
    for name in MODEL_CLASSES:
        if name not in models:
            raise SystemExit(f"{name} is no estimator of the golden file with a model of its own")
    specs = []
    for name, entry in sorted(api.items()):
        if name in ("Pipeline", "PipelineModel"):
            continue
        params = []
        for param in sorted(entry.get("params", []), key=lambda p: p["name"]):
            converter = CONVERTERS[param.get("converter", "identity")]
            params.append(f'        ("{param["name"]}", ParamConverter::{converter}),')
        specs.append(f'    ("{name}", &[')
        specs.extend(params)
        specs.append("    ]),")
    docs = []
    for name, entry in sorted(api.items()):
        params = []
        for param in sorted(entry.get("params", []), key=lambda p: p["name"]):
            params.append(f'        ("{param["name"]}", {rust_str(param["doc"])}),')
        docs.append(f'    ("{name}", &[')
        docs.extend(params)
        docs.append("    ]),")
    out = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// @generated by scripts/gen_ml_stage_kinds.py from tests/golden/ml_api.json;"
        " do not edit.",
        "//! The params of each class of pyspark.ml 4.3.0, with the converter of each (its",
        "//! `typeConverter` in PySpark's `pyspark.ml.param`), and the model class of each",
        "//! estimator whose model is not named with `Model` appended to the estimator's name.",
        "",
        "/// PySpark's converter of a param, which a client applies to each value of the param",
        "/// before it sends the value, as `Param.typeConverter` does. `Identity` takes the value",
        "/// as it is.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub(super) enum ParamConverter {",
        *[f"    {c}," for c in sorted(set(CONVERTERS.values()))],
        "}",
        "",
        "/// The params of each class of pyspark.ml, by the simple name of the class, and the",
        "/// converter of each.",
        "#[rustfmt::skip]",
        "pub(super) const PARAM_CONVERTERS: &[(&str, &[(&str, ParamConverter)])] = &[",
        *specs,
        "];",
        "",
        "/// The JVM class of the model of each estimator (by its simple name) whose model is not",
        "/// named with `Model` appended to the estimator's name.",
        "#[rustfmt::skip]",
        "pub(super) const MODEL_CLASSES: &[(&str, &str)] = &[",
        *[
            line
            for name, model in sorted(models.items())
            for line in (f'    ("{name}",', f'     "{model}"),')
        ],
        "];",
        "",
        "/// The doc of each param of each class of pyspark.ml, by the simple name of the class",
        "/// and the name of the param, as PySpark's `Param.doc` is.",
        "#[rustfmt::skip]",
        "pub(super) const PARAM_DOCS: &[(&str, &[(&str, &str)])] = &[",
        *docs,
        "];",
        "",
    ]
    (ROOT / "crates/spark-connect/src/ml/param_specs.rs").write_text("\n".join(out))


def main():
    api = json.loads((ROOT / "tests/golden/ml_api.json").read_text())
    stage_kinds(api)
    param_specs(api)


if __name__ == "__main__":
    main()
