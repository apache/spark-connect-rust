"""Capture official PySpark 4.3.0's docstrings of the declarations of the drop-in's type stubs.

Each declaration of a stub that scripts/gen_type_stubs.py generates (a function, a class, a
method, a property, an attribute of a docstring, the module) gets the docstring of PySpark's
object of its name at run time, as ``inspect.getdoc`` gives it, which the generator works out of
PySpark's source. This script takes those docstrings of the official client: for the classes of
the stubs of ``pyspark.ml.connect``'s native classes, of PySpark's classes of ``pyspark.ml`` that
they subclass. The golden holds a digest of the docstrings of each stub, the declarations of no
object of PySpark (of the drop-in only, or classic only), and the docstrings of a few samples, which
``python/tests/test_type_stubs_offline.py`` compares with the stubs.

Not PySpark's, and so of no docstring: a docstring that Python makes (of a named tuple or a
dataclass of none) and one that an object inherits of a class of Python (``object.__init__``'s,
``threading.Thread.start``'s), which type checkers of pyspark-client do not show either.

Run with official PySpark 4.3.0 (``pyspark-client``), without a server, from the repository::

    python scripts/capture_stub_docstrings_golden.py --out tests/golden/stub_docstrings.json
"""

import argparse
import ast
import dataclasses
import hashlib
import importlib
import inspect
import json
import os
import tempfile
import warnings
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATED = "# Generated by scripts/gen_type_stubs.py"
# The samples of the golden, of each kind of docstring: of a function, a method, a class
# property, a method of a cast, a class of pyspark.ml.connect, a Connect copy of a classic
# docstring, pyspark.since, the copy of a class body's __doc__, a classmethod whose wrapper's
# __doc__ is set, a cache of functools, and a first line that begins with a space.
SAMPLES = [
    "pyspark.sql.avro.functions:from_avro",
    "pyspark.sql.dataframe:DataFrame.select",
    "pyspark.sql.connect.session:SparkSession.builder",
    "pyspark.sql.column:Column.cast",
    "pyspark.ml.connect.classification:LogisticRegression",
    "pyspark.sql.connect.functions.builtin:col",
    "pyspark.ml.stat:Summarizer.mean",
    "pyspark.sql.connect.tvf:TableValuedFunction",
    "pyspark.sql.connect.session:SparkSession.getActiveSession",
    "pyspark.sql.connect.dataframe:DataFrame.isEmpty",
    "pyspark.ml.connect.feature:Normalizer",
]


def _module_of(stub: Path, python: Path) -> str:
    parts = stub.relative_to(python).with_suffix("").parts
    return ".".join(parts[:-1] if parts[-1] == "__init__" else parts)


def stubs(python: Path):
    """(module, path) of each generated stub under `python`."""
    for path in sorted((python / "pyspark").rglob("*.pyi")):
        if GENERATED in path.read_text():
            yield _module_of(path, python), path


def _string(stmt) -> bool:
    return (
        isinstance(stmt, ast.Expr)
        and isinstance(stmt.value, ast.Constant)
        and isinstance(stmt.value.value, str)
    )


def declarations(module: str, tree: ast.Module):
    """(qualified name, PySpark's module, PySpark's qualified name, the stub's docstring) of each
    declaration of the stub `tree` of `module`, the module itself of the name ""."""
    official = next(
        (
            s.names[0].name
            for s in tree.body
            if isinstance(s, ast.Import) and s.names[0].asname == "_pysparks"
        ),
        None,
    )
    out = [("", module, "", ast.get_docstring(tree))]

    def visit(body, prefix):
        for i, stmt in enumerate(body):
            if isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                accessor = any(
                    isinstance(d, ast.Attribute) and d.attr in ("setter", "deleter")
                    for d in getattr(stmt, "decorator_list", [])
                )
                qualified = prefix + stmt.name
                if not accessor and qualified not in seen:
                    seen.add(qualified)
                    reference = (module, qualified)
                    bases = [ast.unparse(b) for b in getattr(stmt, "bases", [])]
                    if official and bases and bases[-1] == f"_pysparks.{stmt.name}":
                        reference = (official, stmt.name)
                    out.append((qualified, *reference, ast.get_docstring(stmt)))
                if isinstance(stmt, ast.ClassDef):
                    visit(stmt.body, f"{qualified}.")
            elif isinstance(stmt, ast.If):
                visit(stmt.body + stmt.orelse, prefix)
            elif isinstance(stmt, (ast.AnnAssign, ast.Assign)) and i + 1 < len(body):
                target = stmt.target if isinstance(stmt, ast.AnnAssign) else stmt.targets[0]
                qualified = prefix + getattr(target, "id", "")
                if isinstance(target, ast.Name) and _string(body[i + 1]) and qualified not in seen:
                    seen.add(qualified)
                    doc = inspect.cleandoc(body[i + 1].value.value)
                    out.append((qualified, module, qualified, doc))

    seen: set = set()
    visit(tree.body, "")
    return out


def digest(pairs) -> str:
    """The digest of the (qualified name, docstring) pairs of a stub."""
    return hashlib.sha256(json.dumps(sorted(pairs), ensure_ascii=False).encode()).hexdigest()


def _own(obj):
    doc = getattr(obj, "__doc__", None)
    return doc if isinstance(doc, str) else None


def _pysparks(cls) -> bool:
    return cls.__module__.split(".")[0] == "pyspark"


def pyspark_doc(holder, name, obj):
    """``inspect.getdoc(obj)``, of `obj` the attribute `name` of `holder`, but the docstrings that
    are not PySpark's (see the module's docstring)."""
    doc = inspect.getdoc(obj)
    if doc is None:
        return None
    own = _own(obj)
    if inspect.isclass(obj):
        if own is None:
            base = next((b for b in obj.__mro__[1:] if _own(b) is not None), None)
            return doc if base is not None and _pysparks(base) else None
        fields = getattr(obj, "_fields", None)
        if isinstance(fields, tuple):
            arguments = ", ".join(fields) + ("," if len(fields) == 1 else "")
            if own == f"{obj.__name__}({arguments})":
                return None
        if dataclasses.is_dataclass(obj):
            if own == obj.__name__ + str(inspect.signature(obj)).replace(" -> None", ""):
                return None
        return doc
    if own is None and inspect.isclass(holder) and name:
        for base in holder.__mro__:
            member = base.__dict__.get(name)
            if isinstance(member, (staticmethod, classmethod)):
                member = member.__func__
            if member is not None and _own(member) is not None:
                return doc if _pysparks(base) else None
        return None  # of a metaclass, such as type.__call__
    return doc


def reference(module: str, qualified: str):
    """PySpark's docstring of its object `qualified` of `module` at run time, and whether it
    has the object."""
    try:
        holder, obj, name = None, importlib.import_module(module), ""
        for part in qualified.split(".") if qualified else []:
            holder, obj, name = obj, getattr(obj, part), part
    except (ImportError, AttributeError):
        return None, False
    if not qualified:
        return inspect.getdoc(obj), True
    return pyspark_doc(holder, name, obj), True


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=Path("tests/golden/stub_docstrings.json"))
    args = parser.parse_args()
    # PySpark's pyspark.sql.connect.session imports pyspark.testing, which looks for a Spark home.
    os.environ.setdefault("SPARK_HOME", tempfile.mkdtemp())
    warnings.simplefilter("ignore")
    import pyspark

    digests, absent, samples = {}, [], {}
    for module, path in stubs(ROOT / "python"):
        pairs = []
        for qualified, ref_module, ref_qualified, _ in declarations(
            module, ast.parse(path.read_text())
        ):
            key = f"{module}:{qualified}"
            doc, exists = reference(ref_module, ref_qualified)
            if not exists:
                absent.append(key)
                continue
            pairs.append((qualified, doc))
            if key in SAMPLES:
                samples[key] = doc
        digests[module] = digest(pairs)
    missing = sorted(set(SAMPLES) - set(samples))
    if missing:
        raise SystemExit(f"samples of no declaration: {missing}")
    golden = {
        "pyspark": pyspark.__version__,
        "digests": digests,
        "absent": sorted(absent),
        "samples": {key: samples[key] for key in SAMPLES},
    }
    args.out.write_text(json.dumps(golden, indent=1, ensure_ascii=False) + "\n")


if __name__ == "__main__":
    main()
