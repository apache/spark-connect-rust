def test_the_stubs_have_the_docstrings_of_pysparks_objects():
    # A stub replaces its module for a type checker, so an editor shows the docstring of the stub:
    # the stubs had none, so a hover over F.col, DataFrame.select, SparkSession.builder or
    # Column.cast showed no documentation, where it shows PySpark's with pyspark-client. Each
    # declaration of a stub has the docstring of PySpark's object of its name at run time, as
    # inspect.getdoc gives it of the official pyspark-client 4.3.0, of the copies of PySpark
    # Connect (`col.__doc__ = pysparkfuncs.col.__doc__`) and of pyspark.since too
    # (scripts/capture_stub_docstrings_golden.py, which takes them and sets out what is not
    # PySpark's): those of the samples of the golden, and a digest of those of each stub.
    capture = _docstrings_capture()
    golden = json.loads(DOCSTRINGS_GOLDEN.read_text())
    absent = set(golden["absent"])
    digests, samples = {}, {}
    for module, path in capture.stubs(PYTHON_ROOT):
        pairs = []
        for qualified, _, _, doc in capture.declarations(module, ast.parse(path.read_text())):
            key = f"{module}:{qualified}"
            if key not in absent:
                pairs.append((qualified, doc))
                if key in golden["samples"]:
                    samples[key] = doc
        digests[module] = capture.digest(pairs)
    assert samples == golden["samples"]
    assert samples["pyspark.ml.connect.classification:NaiveBayes"].startswith(
        "Naive Bayes Classifiers."
    )
    # A stub of other docstrings than PySpark's, or of other declarations: regenerate the golden
    # with pyspark-client (see the capture script) once its docstrings are checked.
    changed = sorted(m for m in digests if digests[m] != golden["digests"].get(m))
    assert changed == []
    assert sorted(set(golden["digests"]) - set(digests)) == []
