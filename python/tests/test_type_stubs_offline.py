"""Type checkers see PySpark's API on the drop-in, through the stubs of scripts/gen_type_stubs.py.

A type checker reads the source of a module and does not run it. The drop-in's modules whose
classes are native (``from pyspark._pyspark import DataFrameReader``), and pyspark.sql.functions,
whose functions functions.py injects at import time, showed it none of PySpark's annotations:
mypy found 518 of the 562 names of ``pyspark.sql.functions.__all__`` missing, and
``spark.read.json(...)`` was ``Any``. Their ``.pyi`` stubs are PySpark 4.3.0's modules without
their bodies, so mypy sees what it sees of the official pyspark-client.

mypy runs as a user's does: on files of a directory of their own, with the drop-in on the path
of the interpreter as an installed package, whose own errors it does not report.
"""

import importlib
import importlib.util
import os
import pkgutil
import re
import subprocess
import sys
import types
from pathlib import Path

import pytest

pytest.importorskip("mypy")

PYTHON_ROOT = Path(__file__).resolve().parents[1]
USER_APP = Path(__file__).with_name("type_stubs_user_app.py")
GENERATED = "# Generated by scripts/gen_type_stubs.py"

# The public names that the drop-in's modules have at run time and their stubs leave out, as
# PySpark's modules have them, and no API: typing's flag, which the modules import, and the
# variables that the loops of pyspark.sql.types over the type codes of arrays leave behind.
UNDECLARED = {"TYPE_CHECKING"}
UNDECLARED_OF = {"pyspark.sql.types": {"dt", "size"}}


def _stubbed_modules():
    """The modules of the drop-in that have a generated stub, by their import path."""
    modules = []
    for stub in sorted((PYTHON_ROOT / "pyspark").rglob("*.pyi")):
        if GENERATED in stub.read_text():
            parts = stub.relative_to(PYTHON_ROOT).with_suffix("").parts
            modules.append(".".join(parts[:-1] if parts[-1] == "__init__" else parts))
    return modules


def _declared_names(module):
    """The public names of the drop-in's `module` that its stub must declare: all but the
    modules, and the classes and functions of other packages (typing, functools, ...) that the
    module imports for its own use."""
    names = []
    for name, value in sorted(vars(module).items()):
        if name.startswith("_") or name in UNDECLARED | UNDECLARED_OF.get(module.__name__, set()):
            continue
        if isinstance(value, types.ModuleType):
            continue
        if isinstance(value, type) or callable(value):
            origin = getattr(value, "__module__", None)
            if not (isinstance(origin, str) and origin.startswith("pyspark")):
                continue
        names.append(name)
    return names


def _run_mypy(*args, cwd):
    """mypy's diagnostics, (absolute path, line, severity, message) of each, run in `cwd` with
    the drop-in first on the path of the interpreter."""
    path = os.pathsep.join(p for p in (str(PYTHON_ROOT), os.environ.get("PYTHONPATH")) if p)
    result = subprocess.run(
        [sys.executable, "-m", "mypy", "--no-error-summary", "--show-absolute-path", *args],
        cwd=cwd,
        env={**os.environ, "PYTHONPATH": path},
        capture_output=True,
        text=True,
        timeout=600,
    )
    assert result.returncode in (0, 1), result.stdout + result.stderr
    diagnostics = []
    for line in result.stdout.splitlines():
        match = re.match(r"^(.*?):(\d+): (error|note): (.*)$", line)
        if match:
            file, number, severity, message = match.groups()
            diagnostics.append((Path(file).resolve(), int(number), severity, message))
    return diagnostics


@pytest.fixture(scope="module")
def user_mypy(tmp_path_factory):
    """One mypy run over the user's application and the probes of the tests below, in a
    directory of the user, with the drop-in on the interpreter's path."""
    app = tmp_path_factory.mktemp("app")
    (app / USER_APP.name).write_text(USER_APP.read_text())

    import pyspark.sql.functions as F

    functions = ["import pyspark.sql.functions as F"]
    functions += [f"reveal_type(F.{name})" for name in F.__all__]
    (app / "probe_functions.py").write_text("\n".join(functions) + "\n")

    imports, uses, expected = [], [], {}
    for i, name in enumerate(_stubbed_modules()):
        imports.append(f"import {name} as m{i}")
        for attribute in _declared_names(importlib.import_module(name)):
            uses.append(f"m{i}.{attribute}")
    for number, use in enumerate(uses, start=len(imports) + 1):
        expected[number] = use
    (app / "probe_modules.py").write_text("\n".join(imports + uses) + "\n")

    diagnostics = _run_mypy(
        "--cache-dir",
        str(app / ".mypy_cache"),
        USER_APP.name,
        "probe_functions.py",
        "probe_modules.py",
        cwd=app,
    )
    return {
        "app": app,
        "diagnostics": diagnostics,
        "module_uses": expected,
        "functions": list(F.__all__),
    }


def _of(run, file_name):
    return [d[1:] for d in run["diagnostics"] if d[0] == (run["app"] / file_name).resolve()]


def test_user_application_has_only_its_deliberate_error(user_mypy):
    # As on the official client: PySpark's DataFrame, col and reader, and the one error.
    source = USER_APP.read_text().splitlines()
    deliberate = next(i for i, line in enumerate(source, 1) if line.startswith("rows: str ="))
    found = _of(user_mypy, USER_APP.name)
    errors = [(line, message) for line, severity, message in found if severity == "error"]
    assert errors == [
        (
            deliberate,
            'Incompatible types in assignment (expression has type "int", variable has type '
            '"str")  [assignment]',
        )
    ]
    revealed = [m for _, severity, m in found if m.startswith("Revealed type is ")]
    assert revealed[0] == 'Revealed type is "pyspark.sql.dataframe.DataFrame"'
    assert revealed[1] == 'Revealed type is "def (col: str) -> pyspark.sql.column.Column"'
    assert revealed[2].startswith(
        'Revealed type is "def (path: str | list[str] | Any | pyspark.sql.dataframe.DataFrame, '
        "schema: pyspark.sql.types.StructType | str | None =, primitivesAsString: "
    ), revealed[2]
    assert revealed[2].endswith(') -> pyspark.sql.dataframe.DataFrame"'), revealed[2]
    assert len(revealed) == 3


def test_every_function_of_functions_all_is_typed(user_mypy):
    # The 562 names of PySpark's pyspark.sql.functions.__all__, each with its type, none Any.
    found = _of(user_mypy, "probe_functions.py")
    assert [f for f in found if f[1] == "error"] == []
    revealed = [m for _, severity, m in found if m.startswith("Revealed type is ")]
    assert len(revealed) == len(user_mypy["functions"]) == 562
    untyped = [
        name
        for name, message in zip(user_mypy["functions"], revealed)
        if message == 'Revealed type is "Any"'
    ]
    assert untyped == []


def test_stubs_declare_every_public_name_of_their_modules(user_mypy):
    # A stub replaces its module for a type checker, so a name that only the module has, such
    # as the native FrameBound of pyspark.sql.window, would be missing.
    found = _of(user_mypy, "probe_modules.py")
    missing = [
        f"{user_mypy['module_uses'].get(line, line)}: {message}"
        for line, severity, message in found
        if severity == "error"
    ]
    assert missing == []
    assert len(user_mypy["module_uses"]) > 2000


def test_vendored_pandas_udf_stub_has_distinct_overloads():
    # PySpark's own stub of pandas_udf and arrow_udf overloads them on the types of
    # pyspark.sql.types, which were Any without the stubs: mypy reported three overloads that
    # could never match (overload-cannot-match), as they then took the same types.
    stub = Path("pyspark/sql/pandas/functions.pyi")
    diagnostics = _run_mypy("--cache-dir", os.devnull, str(stub), cwd=PYTHON_ROOT)
    assert [d for d in diagnostics if d[0] == PYTHON_ROOT / stub and d[2] == "error"] == []


def test_python_imports_the_module_not_the_stubs():
    # pyspark/sql/functions/ holds only the stubs of PySpark's package pyspark.sql.functions,
    # with no __init__.py: Python imports functions.py, as a module of a directory goes before a
    # namespace package of the same name (PEP 420), and no loader reads a .pyi.
    import pyspark.sql
    import pyspark.sql.functions as F
    import pyspark.sql.functions.builtin as builtin
    import pyspark.sql.functions.partitioning as partitioning

    stubs = PYTHON_ROOT / "pyspark" / "sql" / "functions"
    assert sorted(p.name for p in stubs.iterdir()) == [
        "__init__.pyi",
        "builtin.pyi",
        "partitioning.pyi",
    ]
    assert Path(F.__file__) == PYTHON_ROOT / "pyspark" / "sql" / "functions.py"
    assert importlib.util.find_spec("pyspark.sql.functions").origin == F.__file__
    assert builtin is F.builtin and partitioning is F.partitioning
    assert ("functions", False) in [
        (m.name, m.ispkg) for m in pkgutil.iter_modules(pyspark.sql.__path__)
    ]
