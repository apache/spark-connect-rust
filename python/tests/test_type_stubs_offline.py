def test_the_ml_connect_stubs_declare_the_public_classes_of_the_native_ones():
    # The modules of pyspark.ml.connect of the drop-in's native ML classes replace each by its
    # public class (pyspark.ml._native_classes.publish), a subclass of the public classes of its
    # bases and of PySpark's class of its name of pyspark.ml, which is typed: type checkers saw
    # none of their names (mypy `Any`, pyright `reportPrivateImportUsage` of Pipeline), where
    # PySpark's modules of these paths, its own ML API on torch, are typed. Their stubs declare
    # each class of the bases that it has at run time, of the native stages of pyspark.ml.feature
    # that the package sets in pyspark.ml.connect.feature too. Migrated standard classes are
    # explicit re-exports instead of declarations; check their runtime identity as well.
    from pyspark import _pyspark as native

    checked = []
    stages = set()
    for stub in sorted((PYTHON_ROOT / "pyspark" / "ml" / "connect").glob("*.pyi")):
        name = "pyspark.ml.connect" + ("" if stub.stem == "__init__" else f".{stub.stem}")
        module = importlib.import_module(name)
        tree = ast.parse(stub.read_text())
        official = [
            importlib.import_module(s.names[0].name)
            for s in tree.body
            if isinstance(s, ast.Import) and s.names[0].asname == "_pysparks"
        ]
        for statement in (s for s in tree.body if isinstance(s, ast.ImportFrom)):
            if not statement.module or not statement.module.startswith("pyspark.ml."):
                continue
            for alias in statement.names:
                public = getattr(module, alias.asname or alias.name, None)
                native_class = getattr(native, alias.name, None)
                if (
                    isinstance(public, type)
                    and isinstance(native_class, type)
                    and issubclass(public, native_class)
                ):
                    source = importlib.import_module(statement.module)
                    assert public is getattr(source, alias.name)
                    checked.append(f"{name}.{alias.asname or alias.name}")
        for cls in (s for s in tree.body if isinstance(s, ast.ClassDef)):
            bases = [ast.unparse(b) for b in cls.bases]
            if not bases or not bases[-1].startswith("_pysparks."):
                continue
            public = getattr(module, cls.name)
            # The native class, the public classes of its bases, and PySpark's class.
            assert public.__bases__[0] is getattr(native, cls.name), cls.name
            assert public.__bases__[1:-1] == tuple(getattr(module, b) for b in bases[:-1])
            assert public.__bases__[-1] is getattr(official[0], cls.name)
            checked.append(f"{name}.{cls.name}")
            if name == "pyspark.ml.connect.feature":
                stages.add(cls.name)
    assert stages == set(native._ml_feature_names)
    assert len(checked) > 130


def _stub_declarations(gen, tree):
    """The public names that the stub `tree` declares: (class or None, name) of each name of its
    module and of each member of its classes that exists on the class, not the declarations of
    the attributes of its instances (`x: int` in a class body, the fields of a dataclass)."""

    def names(body, cls):
        out = set()
        for stmt in body:
            if isinstance(stmt, ast.If):
                out |= names(stmt.body + stmt.orelse, cls)
            elif isinstance(stmt, ast.AnnAssign):
                annotation = ast.unparse(stmt.annotation)
                instance = stmt.value is None and not annotation.startswith(("ClassVar", "'Class"))
                dataclass = cls is not None and any(
                    "dataclass" in ast.unparse(d) for d in cls.decorator_list
                )
                named_tuple = cls is not None and any(
                    "NamedTuple" in ast.unparse(b) for b in cls.bases
                )
                if cls is None or named_tuple or not (instance or dataclass):
                    out |= gen.bound_names(stmt)
            elif isinstance(stmt, (ast.Import, ast.ImportFrom)):
                out |= {a.asname for a in stmt.names if a.asname and a.asname == a.name}
            else:
                out |= gen.bound_names(stmt)
        return {n for n in out if not n.startswith("_")}

    found = {(None, name) for name in names(tree.body, None)}
    for qualified, cls in gen._classes(tree.body):
        found |= {(qualified, name) for name in names(cls.body, cls)}
    return found


def _has(gen, obj, name, module):
    """Whether the run-time class or module `obj`, of the module `module`, has `name`: as an
    attribute, or as an attribute of its instances that a method of one of its Python classes
    assigns (`self.returnType = ...`), in the source of its module or of `module`."""
    if hasattr(obj, name):
        return True
    for cls in getattr(obj, "__mro__", ()):
        sources = []
        for source_module in (sys.modules.get(cls.__module__), module):
            try:
                sources.append(inspect.getsource(source_module))
            except (OSError, TypeError):
                continue
        for source in sources:
            for node in ast.walk(ast.parse(source)):
                if isinstance(node, ast.ClassDef) and node.name == cls.__name__:
                    if any(name in gen.assigned_attributes(m) for m in gen._methods(node.body)):
                        return True
    return False


def test_every_name_of_a_stub_exists_at_run_time():
    # A stub replaces its module for a type checker, so a name that only the stub has, such as
    # the py4j converters of PySpark's classic types, type-checks and then fails at run time
    # (`from pyspark.sql.types import DateConverter` raised ImportError). The stubs declare what
    # the drop-in has, but the names of TYPE_ONLY, which PySpark's annotations need.
    gen = _generator()
    missing = set()
    for module, stub in _stubs().items():
        runtime = importlib.import_module(module)
        for cls, name in _stub_declarations(gen, ast.parse(stub.read_text())):
            obj = runtime
            for part in (cls.split(".") if cls else []):
                obj = getattr(obj, part, None)
            if obj is not None and not _has(gen, obj, name, runtime):
                missing.add(f"{module}.{cls}.{name}" if cls else f"{module}.{name}")
    assert sorted(missing - set(TYPE_ONLY)) == []
    assert sorted(set(TYPE_ONLY) - missing) == []


